// Helper to interpolate between two poses with smooth easing
export function interpolatePoses(poseA: DancePose, poseB: DancePose, t: number): DancePose {
  // Smooth sine/cubic ease-in-out
  const eased = t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2;

  const lerp = (a: number, b: number) => a + (b - a) * eased;

  return {
    hipX: lerp(poseA.hipX, poseB.hipX),
    hipY: lerp(poseA.hipY, poseB.hipY),
    hipZ: lerp(poseA.hipZ, poseB.hipZ),
    hipRotX: lerp(poseA.hipRotX, poseB.hipRotX),
    hipRotY: lerp(poseA.hipRotY, poseB.hipRotY),
    hipRotZ: lerp(poseA.hipRotZ, poseB.hipRotZ),

    spineRotX: lerp(poseA.spineRotX, poseB.spineRotX),
    spineRotY: lerp(poseA.spineRotY, poseB.spineRotY),
    spineRotZ: lerp(poseA.spineRotZ, poseB.spineRotZ),
    chestRotX: lerp(poseA.chestRotX, poseB.chestRotX),
    chestRotY: lerp(poseA.chestRotY, poseB.chestRotY),
    chestRotZ: lerp(poseA.chestRotZ, poseB.chestRotZ),

    leftShoulderLift: lerp(poseA.leftShoulderLift, poseB.leftShoulderLift),
    rightShoulderLift: lerp(poseA.rightShoulderLift, poseB.rightShoulderLift),

    headRotX: lerp(poseA.headRotX, poseB.headRotX),
    headRotY: lerp(poseA.headRotY, poseB.headRotY),
    headRotZ: lerp(poseA.headRotZ, poseB.headRotZ),

    leftShoulderRotX: lerp(poseA.leftShoulderRotX, poseB.leftShoulderRotX),
    leftShoulderRotY: lerp(poseA.leftShoulderRotY, poseB.leftShoulderRotY),
    leftShoulderRotZ: lerp(poseA.leftShoulderRotZ, poseB.leftShoulderRotZ),
    leftElbowFlex: lerp(poseA.leftElbowFlex, poseB.leftElbowFlex),
    leftWristRot: lerp(poseA.leftWristRot, poseB.leftWristRot),
    leftHandShape: t > 0.5 ? poseB.leftHandShape : poseA.leftHandShape,

    rightShoulderRotX: lerp(poseA.rightShoulderRotX, poseB.rightShoulderRotX),
    rightShoulderRotY: lerp(poseA.rightShoulderRotY, poseB.rightShoulderRotY),
    rightShoulderRotZ: lerp(poseA.rightShoulderRotZ, poseB.rightShoulderRotZ),
    rightElbowFlex: lerp(poseA.rightElbowFlex, poseB.rightElbowFlex),
    rightWristRot: lerp(poseA.rightWristRot, poseB.rightWristRot),
    rightHandShape: t > 0.5 ? poseB.rightHandShape : poseA.rightHandShape,

    leftHipRotX: lerp(poseA.leftHipRotX, poseB.leftHipRotX),
    leftHipRotY: lerp(poseA.leftHipRotY, poseB.leftHipRotY),
    leftHipRotZ: lerp(poseA.leftHipRotZ, poseB.leftHipRotZ),
    leftKneeFlex: lerp(poseA.leftKneeFlex, poseB.leftKneeFlex),
    leftFootRotX: lerp(poseA.leftFootRotX, poseB.leftFootRotX),
    leftFootRotY: lerp(poseA.leftFootRotY, poseB.leftFootRotY),

    rightHipRotX: lerp(poseA.rightHipRotX, poseB.rightHipRotX),
    rightHipRotY: lerp(poseA.rightHipRotY, poseB.rightHipRotY),
    rightHipRotZ: lerp(poseA.rightHipRotZ, poseB.rightHipRotZ),
    rightKneeFlex: lerp(poseA.rightKneeFlex, poseB.rightKneeFlex),
    rightFootRotX: lerp(poseA.rightFootRotX, poseB.rightFootRotX),
    rightFootRotY: lerp(poseA.rightFootRotY, poseB.rightFootRotY),
  };
}
